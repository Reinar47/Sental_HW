CREATE TABLE IF NOT EXISTS armor
(
    armor_id                     bigint GENERATED BY DEFAULT AS IDENTITY   PRIMARY KEY,
    armor_name                   varchar(30)                               NOT NULL,
    armor_class                  varchar(30)                               NOT NULL,
    armor_weight                 integer                                   NOT NULL,
    armor_description            varchar(255)                              NOT NULL,
    armor_equipped               boolean                                   NOT NULL
);

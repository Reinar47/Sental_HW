CREATE TABLE IF NOT EXISTS weapon
(
    weapon_id                      bigint GENERATED BY DEFAULT AS IDENTITY        PRIMARY KEY,
    weapon_name                    varchar(30)                                    NOT NULL,
    weapon_dmg                     varchar(30)                                    NOT NULL,
    weapon_bonus                   varchar(30)                                    NOT NULL,
    weapon_type                    varchar(30)                                    NOT NULL,
    weapon_description             varchar(255)                                   NOT NULL,
    weapon_equipped                boolean                                        NOT NULL,
    "range"                        integer                                        NOT NULL,
    weapon_weight                  integer                                        NOT NULL
);

CREATE TABLE IF NOT EXISTS game_monster
(
    monster_id                     bigint GENERATED BY DEFAULT AS IDENTITY          PRIMARY KEY,
    monster_name                   varchar(255)                                     NOT NULL,
    monster_type                   varchar(30),
    monster_description            varchar(255),
    monster_str                    integer                                          NOT NULL,
    monster_dex                    integer                                          NOT NULL,
    monster_con                    integer                                          NOT NULL,
    monster_int                    integer                                          NOT NULL,
    monster_wis                    integer                                          NOT NULL,
    monster_cha                    integer                                          NOT NULL,
    monster_deleted                boolean                                          NOT NULL
);

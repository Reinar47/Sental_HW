CREATE TABLE IF NOT EXISTS game_character
(
    character_id                      bigint GENERATED BY DEFAULT AS IDENTITY          PRIMARY KEY,
    character_name                    varchar(30)                                      NOT NULL,
    experience                        integer                                          NOT NULL,
    hit_points                        integer                                          NOT NULL,
    max_hitpoints                     integer                                          NOT NULL,
    level                             integer                                          NOT NULL,
    is_deleted                        boolean                                          NOT NULL,
    ability_scores_id                 bigint                                           UNIQUE,
    race_id                           bigint                                           NOT NULL,
    class_id                          bigint                                           NOT NULL,
    armor_id                          bigint                                           NOT NULL,
    user_id                           bigint                                           NOT NULL,

    CONSTRAINT fk_game_character_ability_scores
        FOREIGN KEY (ability_scores_id) REFERENCES ability_scores (ability_scores_id),
    CONSTRAINT fk_game_character_race
        FOREIGN KEY (race_id) REFERENCES character_race (race_id),
    CONSTRAINT fk_game_character_class
        FOREIGN KEY (class_id) REFERENCES character_class (class_id),
    CONSTRAINT fk_game_character_armor
        FOREIGN KEY (armor_id) REFERENCES armor (armor_id),
    CONSTRAINT fk_game_character_user
        FOREIGN KEY (user_id) REFERENCES user_account (user_id)
);

CREATE TABLE IF NOT EXISTS ability_scores
(
    ability_scores_id                bigint GENERATED BY DEFAULT AS IDENTITY      PRIMARY KEY,
    ability_score_points             integer                                      NOT NULL,
    strength_value                   integer                                      NOT NULL,
    strength_modifier                integer                                      NOT NULL,
    dexterity_value                  integer                                      NOT NULL,
    dexterity_modifier               integer                                      NOT NULL,
    constitution_value               integer                                      NOT NULL,
    constitution_modifier            integer                                      NOT NULL,
    intelligence_value               integer                                      NOT NULL,
    intelligence_modifier            integer                                      NOT NULL,
    wisdom_value                     integer                                      NOT NULL,
    wisdom_modifier                  integer                                      NOT NULL,
    charisma_value                   integer                                      NOT NULL,
    charisma_modifier                integer                                      NOT NULL
);
